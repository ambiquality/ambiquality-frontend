/**
 * Country `SelectOption`s sorted by localized display name, recomputed when the UI language changes.
 * Falls back to the bare ISO code if `Intl.DisplayNames` can't resolve a name (or isn't available).
 */
export function useCountryOptions(): ReadonlyArray<SelectOption> {
  const { i18n } = useTranslation();
  const language = i18n.language;

  return useMemo(() => {
    let display: Intl.DisplayNames | undefined;
    try {
      display = new Intl.DisplayNames([language], { type: 'region' });
    } catch {
      display = undefined;
    }

    const collator = new Intl.Collator(language, { sensitivity: 'base' });
    return ISO_3166_ALPHA2.map((code) => ({
      value: code,
      label: display?.of(code) ?? code,
    })).sort((a, b) => collator.compare(a.label, b.label));
  }, [language]);
}
